//! Discriminator: what an UNCOMPENSATED tracking-reference delay does to
//! the amplitude readout of a fast log sweep.
//!
//! The mechanism under test is a pure DSP property, so it needs no chassis. The
//! lock-in inside [`AdaptiveTrackingFilter`] demodulates the incoming sample
//! against a reference advanced at the frequency the caller passes in. In the
//! closed sine loop that caller is the NCO, and the sample arriving on this
//! frame is an echo of drive emitted `lag` frames earlier - so the reference
//! runs at `f(n)` while the signal sits at `f(n - lag)`. The difference beats
//! the wanted phasor OFF baseband by `Δf`, and the two-pole baseband low-pass
//! attenuates it by
//!
//! ```text
//!   D = 1 / (1 + (Δf / bw)^2)
//! ```
//!
//! which is a systematic UNDER-READ that grows with frequency (Δf is
//! proportional to f under a log law). The servo, seeing an under-read,
//! overdrives the true response by exactly `1/D` - and only the raw-ring
//! watchdog, which never touches the demodulated path, can see the real level.
//!
//! F1 (the favored mechanism) predicts ~4 dB of droop at 276 Hz and ~9.5 dB at
//! 500 Hz for the probe's configuration (`FixedHz(10)`, 60 oct/min, 2089-frame
//! lag). F2 (a real ~276 Hz electrical feature on the bench) predicts NO droop
//! here at all, and a trip frequency that does not move with the sweep rate.
//!
//! The sweep-rate scaling row is the second half of the discriminator: halving
//! the rate halves Δf, which moves an F1 trip a long way UP the band. An F2
//! trip would stay pinned at 276 Hz.

use hertzforge_dsp::sweep::{SweepOscillator, SweepRate};
use hertzforge_dsp::tracking::{AdaptiveTrackingFilter, BandwidthMode};

/// The probe's acquisition rate.
const FS: f64 = 51_200.0;
/// The probe's sweep band.
const F_LO: f64 = 60.0;
const F_HI: f64 = 500.0;
/// The engage lead-in + hardware round trip measured on the chassis.
const LAG_FRAMES: usize = 2089;

/// Run a constant-amplitude log sweep through the filter with the input delayed
/// by `lag` frames relative to the reference, and return
/// `(reference_frequency_hz, amplitude_read)` samples decimated for reporting.
///
/// The signal is generated by a phase-continuous NCO stepped by the same law
/// that drives the reference, then pushed through a `lag`-deep delay line. That
/// is exactly the physical arrangement: one oscillator, two observation points
/// separated by the loop transport delay.
fn swept_readout(
    bw: BandwidthMode,
    oct_per_min: f64,
    lag: usize,
    amp_true: f64,
) -> Vec<(f64, f64)> {
    let law = SweepRate::LogOctPerMin(oct_per_min);
    let n = (hertzforge_dsp::sweep::sweep_seconds(F_LO, F_HI, law) * FS).ceil() as usize;
    let mut osc = SweepOscillator::new(FS, F_LO);
    let mut filt = AdaptiveTrackingFilter::new(FS, bw);
    // Delay line: `lag` frames of the generated tone, zero-filled at the start
    // (the drive has not reached the sensor yet).
    let mut delay = vec![0.0f64; lag + 1];
    let mut w = 0usize;
    let mut out = Vec::with_capacity(n / 512 + 1);
    for k in 0..n {
        let t = k as f64 / FS;
        osc.set_frequency(law.freq_at(F_LO, t));
        let (s, f_ref, _theta) = osc.next();
        // Push this frame's true tone in, pop the frame from `lag` ago out.
        delay[w] = amp_true * s;
        w = (w + 1) % delay.len();
        let delayed = delay[w];
        let (a, _ph) = filt.update(delayed, f_ref);
        if k % 512 == 0 {
            out.push((f_ref, a));
        }
    }
    out
}

/// Amplitude read at (or just past) `f_hz` from a `swept_readout` table.
fn read_at(table: &[(f64, f64)], f_hz: f64) -> f64 {
    table
        .iter()
        .find(|(f, _)| *f >= f_hz)
        .map(|(_, a)| *a)
        .unwrap_or_else(|| table.last().map(|(_, a)| *a).unwrap_or(0.0))
}

fn db(ratio: f64) -> f64 {
    20.0 * ratio.log10()
}

/// Closed-form F1 prediction: the two-pole baseband low-pass magnitude at the
/// beat frequency `Δf = f - f/2^(R*lag/fs/60)`.
fn f1_predicted_db(f_hz: f64, oct_per_min: f64, lag: usize, bw_hz: f64) -> f64 {
    let ratio = (oct_per_min * (lag as f64 / FS) / 60.0).exp2();
    let df = f_hz - f_hz / ratio;
    db(1.0 / (1.0 + (df / bw_hz).powi(2)))
}

/// THE DISCRIMINATOR. A constant-amplitude 60 -> 500 Hz sweep at 60 oct/min,
/// delayed 2089 frames against a `FixedHz(10)` tracking filter, must show the
/// F1 droop: several dB of systematic UNDER-READ, growing with frequency, and
/// matching the closed-form two-pole prediction.
///
/// This is the whole basis of the tracking-reference delay compensation. If it did
/// not reproduce, the ~276 Hz chassis trips would have to be a real bench feature
/// instead.
#[test]
fn delayed_reference_droops_the_amplitude_readout() {
    let bw_hz = 10.0;
    let table = swept_readout(BandwidthMode::FixedHz(bw_hz), 60.0, LAG_FRAMES, 1.0);

    println!("  f_ref (Hz)   read (EU)   error (dB)   F1 predicted (dB)");
    for probe in [80.0, 120.0, 180.0, 240.0, 276.0, 350.0, 420.0, 500.0] {
        let a = read_at(&table, probe);
        println!(
            "  {:>8.1}   {:>9.5}   {:>+10.2}   {:>+16.2}",
            probe,
            a,
            db(a),
            f1_predicted_db(probe, 60.0, LAG_FRAMES, bw_hz)
        );
    }

    // The two headline numbers from the original report.
    let at_276 = db(read_at(&table, 276.0));
    let at_500 = db(read_at(&table, 500.0));
    assert!(
        (-5.5..=-2.5).contains(&at_276),
        "F1 predicts ~-4 dB of droop at 276 Hz; measured {at_276:+.2} dB"
    );
    assert!(
        (-11.5..=-7.5).contains(&at_500),
        "F1 predicts ~-9.5 dB of droop at 500 Hz; measured {at_500:+.2} dB"
    );
    // Monotone worsening with frequency is the signature that separates a
    // transport-delay droop from a fixed spectral feature.
    assert!(
        at_500 < at_276,
        "droop must deepen with frequency: {at_276:+.2} dB at 276, {at_500:+.2} dB at 500"
    );
}

/// The sweep-rate row - the half of the discriminator that a chassis could also
/// run. Halving the rate halves `Δf` at every frequency, so the droop at a FIXED
/// frequency collapses and the frequency at which a given droop is reached moves
/// a long way up the band: past the top of the probe's own 60-500 Hz sweep. An
/// F2 (real ~276 Hz bench feature) explanation predicts no such movement - the
/// trip would stay pinned at 276 Hz at any rate.
#[test]
fn droop_scales_with_sweep_rate_not_with_frequency_alone() {
    let bw_hz = 10.0;
    let fast = swept_readout(BandwidthMode::FixedHz(bw_hz), 60.0, LAG_FRAMES, 1.0);
    let half = swept_readout(BandwidthMode::FixedHz(bw_hz), 30.0, LAG_FRAMES, 1.0);

    let fast_276 = db(read_at(&fast, 276.0));
    let half_276 = db(read_at(&half, 276.0));
    println!("  276 Hz @ 60 oct/min: {fast_276:+.2} dB");
    println!("  276 Hz @ 30 oct/min: {half_276:+.2} dB");

    // Where does each rate FIRST reach the fast run's 276 Hz droop? Start the
    // search above 80 Hz so the filter's own start-up transient (which reads
    // zero, i.e. -inf dB) cannot answer the question.
    let target = fast_276;
    let cross = |t: &[(f64, f64)]| -> Option<f64> {
        t.iter()
            .filter(|(f, _)| *f >= 80.0)
            .find(|(_, a)| db(*a) <= target)
            .map(|(f, _)| *f)
    };
    let fast_cross = cross(&fast).expect("the 60 oct/min run reaches its own droop");
    println!(
        "  droop {target:+.2} dB first reached at: 60 oct/min -> {fast_cross:.0} Hz, \
         30 oct/min -> {:?} (band tops out at {F_HI:.0} Hz)",
        cross(&half)
    );

    assert!(
        half_276 > fast_276 + 2.0,
        "halving the rate must materially reduce the droop at a fixed frequency: \
         {fast_276:+.2} dB -> {half_276:+.2} dB"
    );
    assert!(
        (250.0..=300.0).contains(&fast_cross),
        "the 60 oct/min equal-droop point is the observed trip neighborhood; got {fast_cross:.0} Hz"
    );
    assert!(
        cross(&half).is_none(),
        "at 30 oct/min the equal-droop point must move ABOVE the 60-500 Hz band \
         (closed form puts it near {:.0} Hz), so the probe would not trip at all; \
         found it at {:?} instead",
        equal_droop_freq(target, 30.0, LAG_FRAMES, bw_hz),
        cross(&half)
    );
    // The closed form says where it went: ~540 Hz, not 276 Hz.
    let moved_to = equal_droop_freq(target, 30.0, LAG_FRAMES, bw_hz);
    assert!(
        (500.0..600.0).contains(&moved_to),
        "closed-form equal-droop frequency at 30 oct/min should land near 540 Hz; got {moved_to:.0} Hz"
    );
}

/// Inverse of [`f1_predicted_db`]: the frequency at which the F1 droop equals
/// `target_db` for a given rate / lag / bandwidth.
fn equal_droop_freq(target_db: f64, oct_per_min: f64, lag: usize, bw_hz: f64) -> f64 {
    let d = 10f64.powf(target_db / 20.0);
    let df_needed = bw_hz * (1.0 / d - 1.0).sqrt();
    let ratio = (oct_per_min * (lag as f64 / FS) / 60.0).exp2();
    df_needed / (1.0 - 1.0 / ratio)
}

/// The CONTROL for the discriminator: with no transport delay, the very same
/// sweep reads flat. This is what proves the droop above is the delay and not
/// the sweep rate beating the filter's own settling.
#[test]
fn undelayed_reference_reads_flat_on_the_same_sweep() {
    let table = swept_readout(BandwidthMode::FixedHz(10.0), 60.0, 0, 1.0);
    // Skip the filter's own start-up settling (1/bw = 100 ms at 60 oct/min is
    // ~0.1 octave, i.e. the first ~64 Hz).
    for &(f, a) in table.iter().filter(|(f, _)| *f > 70.0) {
        assert!(
            db(a).abs() < 0.5,
            "undelayed readout must be flat: {:+.2} dB at {f:.1} Hz",
            db(a)
        );
    }
}

/// THE FIX, at the DSP level: run the identical delayed sweep but
/// advance the demodulation reference at the frequency the NCO held `lag` frames
/// ago instead of the frequency it holds now. The droop disappears.
///
/// This is the whole compensation - one argument, delayed. The reference phase
/// then equals the drive phase at `n - lag` plus the constant `2*pi*f0*tau`
/// accumulated over the seeded startup, and a constant phase offset does not
/// touch the magnitude.
#[test]
fn delaying_the_reference_frequency_removes_the_droop() {
    let table = compensated_readout(BandwidthMode::FixedHz(10.0), 60.0, LAG_FRAMES, 1.0);
    println!("  f_ref (Hz)   read (EU)   error (dB)");
    let mut worst = 0.0f64;
    for &(f, a) in table.iter().filter(|(f, _)| *f > 80.0) {
        let e = db(a);
        if e.abs() > worst.abs() {
            worst = e;
        }
        if (f as i64) % 100 < 3 {
            println!("  {f:>8.1}   {a:>9.5}   {e:>+10.2}");
        }
    }
    println!("  worst error above 80 Hz: {worst:+.3} dB");
    assert!(
        worst.abs() <= 0.5,
        "the compensated readout must be flat to 0.5 dB; worst {worst:+.3} dB"
    );
}

/// Same sweep as [`swept_readout`], but the reference advances at the frequency
/// the NCO held `lag` frames ago - which is the frequency of the signal actually
/// arriving. Startup is seeded with `F_LO`, exactly as the step seeds its ring.
fn compensated_readout(
    bw: BandwidthMode,
    oct_per_min: f64,
    lag: usize,
    amp_true: f64,
) -> Vec<(f64, f64)> {
    let law = SweepRate::LogOctPerMin(oct_per_min);
    let n = (hertzforge_dsp::sweep::sweep_seconds(F_LO, F_HI, law) * FS).ceil() as usize;
    let mut osc = SweepOscillator::new(FS, F_LO);
    let mut filt = AdaptiveTrackingFilter::new(FS, bw);
    let mut delay = vec![0.0f64; lag + 1];
    let mut freqs = vec![F_LO; lag + 1];
    let mut w = 0usize;
    let mut out = Vec::with_capacity(n / 512 + 1);
    for k in 0..n {
        let t = k as f64 / FS;
        osc.set_frequency(law.freq_at(F_LO, t));
        let (s, f_now, _theta) = osc.next();
        delay[w] = amp_true * s;
        freqs[w] = f_now;
        w = (w + 1) % delay.len();
        let delayed = delay[w];
        let f_ref = freqs[w];
        let (a, _ph) = filt.update(delayed, f_ref);
        if k % 512 == 0 {
            out.push((f_now, a));
        }
    }
    out
}

/// The compensation is a NO-OP at zero lag: byte-identical output, not merely
/// close. This is what lets it be on by default - HERTZFORGE-SIM measures a zero lag
/// and is therefore untouched.
#[test]
fn compensation_is_byte_identical_at_zero_lag() {
    let a = swept_readout(BandwidthMode::FixedHz(10.0), 60.0, 0, 1.0);
    let b = compensated_readout(BandwidthMode::FixedHz(10.0), 60.0, 0, 1.0);
    assert_eq!(a.len(), b.len());
    for (i, ((fa, aa), (fb, ab))) in a.iter().zip(b.iter()).enumerate() {
        assert_eq!(fa, fb, "sample {i}");
        assert_eq!(aa, ab, "sample {i}: {aa} vs {ab}");
    }
}

/// The DEPLOYED default configuration is structurally immune, and this is the
/// row that says so in code: proportional bandwidth at 1 oct/min reads flat
/// across the same band with the same 2089-frame lag.
#[test]
fn default_config_is_structurally_immune() {
    let table = swept_readout(
        BandwidthMode::Proportional {
            pct: 5.0,
            max_hz: 20.0,
        },
        1.0,
        LAG_FRAMES,
        1.0,
    );
    for &(f, a) in table.iter().filter(|(f, _)| *f > 70.0) {
        assert!(
            db(a).abs() < 0.5,
            "the deployed default must not droop: {:+.2} dB at {f:.1} Hz",
            db(a)
        );
    }
}
